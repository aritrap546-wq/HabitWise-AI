# 2. CREATE PROTOTYPE AI MODEL
# ============================================================
# Prototype training data.
# This is synthetic data for demonstration/model development.

rng = np.random.default_rng(42)

training_data = []

for _ in range(1500):

    achievement = rng.uniform(20, 120)
    consistency = rng.uniform(10, 100)
    weak_ratio = rng.uniform(0, 1)

    if achievement >= 90 and consistency >= 75:
        label = "Excellent"

    elif achievement >= 75 and consistency >= 60:
        label = "Good"

    elif achievement >= 50 and consistency >= 40:
        label = "Improving"

    else:
        label = "Needs Attention"

    training_data.append(
        [achievement, consistency, weak_ratio, label]
    )

training_df = pd.DataFrame(
    training_data,
    columns=[
        "Achievement",
        "Consistency",
        "Weak Habit Ratio",
        "Label"
    ]
)

X = training_df[
    [
        "Achievement",
        "Consistency",
        "Weak Habit Ratio"
    ]
]

y = training_df["Label"]

ai_model = DecisionTreeClassifier(
    max_depth=4,
    random_state=42
)

ai_model.fit(X, y)


