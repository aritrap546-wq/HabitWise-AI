def analyze_day(selected_habits, *values):

    if not selected_habits:

        return (
            """
            <div class="card">
                <h2>⚠️ No habits selected</h2>
                <p>Please select at least one habit.</p>
            </div>
            """,
            "",
            ""
        )

    # Map 20 inputs to 20 habits
    records = []

    for i, habit in enumerate(HABIT_NAMES):

        if habit not in selected_habits:
            continue

        unit, target = HABITS[habit]

        actual = values[i]

        if actual is None:
            actual = 0

        actual = max(float(actual), 0)

        achievement = (
            actual / target * 100
            if target > 0 else 0
        )

        records.append({
            "Habit": habit,
            "Unit": unit,
            "Target": target,
            "Actual": actual,
            "Achievement": achievement
        })

    if not records:

        return (
            """
            <div class="card">
                <h2>⚠️ No data entered</h2>
                <p>Please enter today's performance.</p>
            </div>
            """,
            "",
            ""
        )

    df = pd.DataFrame(records)

    # ========================================================
    # DAILY CALCULATIONS
    # ========================================================

    # Cap each habit at 100% for overall daily scoring
    capped_scores = np.minimum(
        df["Achievement"].values,
        100
    )

    overall_score = float(
        np.mean(capped_scores)
    )

    # 80% achievement = habit considered reasonably on target
    habits_on_target = int(
        np.sum(df["Achievement"] >= 80)
    )

    consistency = (
        habits_on_target / len(df)
    ) * 100

    weak_habits = int(
        np.sum(df["Achievement"] < 60)
    )

    weak_ratio = (
        weak_habits / len(df)
    )

    # ========================================================
    # DECISION TREE AI
    # ========================================================

    model_input = pd.DataFrame([{
        "Achievement": overall_score,
        "Consistency": consistency,
        "Weak Habit Ratio": weak_ratio
    }])

    prediction = ai_model.predict(
        model_input
    )[0]

    probabilities = ai_model.predict_proba(
        model_input
    )[0]

    confidence = (
        float(np.max(probabilities)) * 100
    )

    # ========================================================
    # STATUS COLOUR
    # ========================================================

    colours = {
        "Excellent": "#16a34a",
        "Good": "#2563eb",
        "Improving": "#d97706",
        "Needs Attention": "#dc2626"
    }

    emojis = {
        "Excellent": "🌟",
        "Good": "✅",
        "Improving": "📈",
        "Needs Attention": "⚠️"
    }

    colour = colours[prediction]
    emoji = emojis[prediction]

    # ========================================================
    # ANALYSIS MESSAGE
    # ========================================================

    messages = {
        "Excellent":
            "Excellent performance today! Your selected habits are "
            "well on track. Keep maintaining this routine.",

        "Good":
            "Your habits are generally on track. A little more "
            "consistency can make your routine even stronger.",

        "Improving":
            "You are making progress, but some habits need more "
            "attention. Focus on gradual improvement.",

        "Needs Attention":
            "Several habits need attention today. Focus on a few "
            "important habits and improve them gradually."
    }

    # ========================================================
    # STRONGEST / WEAKEST
    # ========================================================

    strongest = df.loc[
        df["Achievement"].idxmax()
    ]

    weakest = df.loc[
        df["Achievement"].idxmin()
    ]

    weak_names = df.loc[
        df["Achievement"] < 60,
        "Habit"
    ].tolist()

    weak_text = (
        ", ".join(weak_names)
        if weak_names
        else "None 🎉"
    )

    # ========================================================
    # HTML REPORT
    # ========================================================

    report = f"""

    <div class="hero">
        <div class="logo">🌱 HabitWise AI</div>
        <div class="subtitle">
            Daily Habit Analysis • {date.today().strftime("%d %B %Y")}
        </div>
    </div>

    <div class="score-card">

        <div class="score-label">
            TODAY'S OVERALL SCORE
        </div>

        <div class="score-number">
            {overall_score:.1f}%
        </div>

        <div class="progress-background">
            <div class="progress-fill"
                 style="width:{min(overall_score,100)}%;
                        background:{colour};">
            </div>
        </div>

        <div class="prediction"
             style="color:{colour} !important;">
            {emoji} {prediction.upper()}
        </div>

        <div style="color:#64748b !important; margin-top:8px;">
            AI confidence: {confidence:.1f}%
        </div>

    </div>


    <div class="card">

        <div class="section-heading">
            🤖 AI Analysis
        </div>

        <p>
            {messages[prediction]}
        </p>

        <div class="stats">

            <div class="stat">
                <div class="stat-value">
                    {overall_score:.1f}%
                </div>
                <div class="stat-name">
                    Overall Achievement
                </div>
            </div>

            <div class="stat">
                <div class="stat-value">
                    {consistency:.1f}%
                </div>
                <div class="stat-name">
                    Habit Consistency
                </div>
            </div>

            <div class="stat">
                <div class="stat-value">
                    {weak_habits}
                </div>
                <div class="stat-name">
                    Needs Attention
                </div>
            </div>

        </div>

    </div>


    <div class="card">

        <div class="section-heading">
            🏆 Strongest Habit
        </div>

        <p>
            <b>{strongest['Habit']}</b> —
            {strongest['Achievement']:.1f}% of today's target.
        </p>

    </div>


    <div class="card">

        <div class="section-heading">
            ⚠️ Habits Needing Attention
        </div>

        <p>
            {weak_text}
        </p>

    </div>


    <div class="recommendation">

        <h2>💡 HabitWise Recommendation</h2>

        <p>
            Focus first on <b>{weakest['Habit']}</b>.
            Your current achievement is
            <b>{weakest['Achievement']:.1f}%</b>.
            Try a realistic improvement tomorrow instead of
            making a very large change at once.
        </p>

    </div>

    """

    # ========================================================
    # TABLE
    # ========================================================

    table = """

    <div class="performance-card">

        <h2 style="color:#0f172a !important;">
            📊 Today's Performance
        </h2>

        <table class="habit-table">

            <thead>
                <tr>
                    <th>Habit</th>
                    <th>Unit</th>
                    <th>Target</th>
                    <th>Actual</th>
                    <th>Achievement</th>
                </tr>
            </thead>

            <tbody>
    """

    for _, row in df.iterrows():

        achievement = float(
            row["Achievement"]
        )

        if achievement >= 90:
            badge_colour = "#15803d"
            badge_bg = "#dcfce7"

        elif achievement >= 60:
            badge_colour = "#b45309"
            badge_bg = "#fef3c7"

        else:
            badge_colour = "#b91c1c"
            badge_bg = "#fee2e2"

        table += f"""

            <tr>

                <td>
                    <b>{row['Habit']}</b>
                </td>

                <td>
                    {row['Unit']}
                </td>

                <td>
                    {row['Target']}
                </td>

                <td>
                    {row['Actual']}
                </td>

                <td>

                    <span style="
                    color:{badge_colour} !important;
                    background:{badge_bg};
                    padding:6px 12px;
                    border-radius:8px;
                    font-weight:700;
                    display:inline-block;">
                        {achievement:.1f}%
                    </span>

                </td>

            </tr>

        """

    table += """

            </tbody>

        </table>

    </div>

    """

    return (
        report,
        table,
        prediction
    )


